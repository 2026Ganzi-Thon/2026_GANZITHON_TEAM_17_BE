import org.springframework.transaction.support.TransactionTemplate;
import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;
import static org.assertj.core.api.Assertions.assertThat;

@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class ReplyLikeConcurrencyTest extends IntegrationTestSupport {
    @Autowired UserRepository users;
    @Autowired WorryRepository worries;
    @Autowired ReplyRepository replies;
    @Autowired ReplyLikeService service;
    @Autowired JdbcTemplate jdbc;
    @Autowired DatabaseCleaner cleaner;
    @Autowired PlatformTransactionManager transactions;
    @BeforeAll void create() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS reply_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reply_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL, UNIQUE(reply_id,user_id))");
    }
    @AfterAll void clean() { cleaner.clean(); jdbc.execute("DROP TABLE IF EXISTS reply_likes"); }
    @Test void 동시_토글은_추가와_취소로_처리된다() throws Exception {
        User youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "동시답청년"));
        User senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "동시답선배"));
        Worry worry = worries.saveAndFlush(Worry.of(youth, "제목", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Reply reply = replies.saveAndFlush(Reply.text(worry, senior, "답장"));
        var pool = Executors.newFixedThreadPool(2);
        try {
            CountDownLatch ready = new CountDownLatch(2), go = new CountDownLatch(1);
            java.util.concurrent.Callable<ReplyLikeResponse> action = () -> { ready.countDown(); go.await(); return service.toggle(youth.getId(), reply.getId()); };
            var first = pool.submit(action); var second = pool.submit(action);
            assertThat(ready.await(10, TimeUnit.SECONDS)).isTrue(); go.countDown();
            var result = List.of(first.get(30, TimeUnit.SECONDS), second.get(30, TimeUnit.SECONDS));
            assertThat(result).extracting(ReplyLikeResponse::likedByMe).containsExactlyInAnyOrder(true, false);
            assertThat(result).extracting(ReplyLikeResponse::likeCount).containsExactlyInAnyOrder(1L, 0L);
        } finally { pool.shutdownNow(); }
    }

    @Test void 비공개_변경을_기다린_후_좋아요를_거부한다() throws Exception {
        checkWaitAndReject("visibility", ReplyErrorCode.FORBIDDEN_VIEW);
    }

    @Test void 답장_삭제를_기다린_후_좋아요를_거부한다() throws Exception {
        checkWaitAndReject("delete", ReplyErrorCode.NOT_FOUND);
    }

    @Test void 답장_신고_숨김을_기다린_후_좋아요를_거부한다() throws Exception {
        checkWaitAndReject("hide", ReplyErrorCode.FORBIDDEN_VIEW);
    }

    // 상태 변경을 별도 트랜잭션에서 커밋해 좋아요가 잠금을 기다린 뒤 재확인하는지 검증한다.
    private void checkWaitAndReject(String change, ReplyErrorCode expected) throws Exception {
        String suffix = java.util.UUID.randomUUID().toString().substring(0, 5);
        User youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "청" + suffix));
        User senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "선" + suffix));
        Worry worry = worries.saveAndFlush(Worry.of(youth, "제목", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Reply reply = replies.saveAndFlush(Reply.text(worry, senior, "답장"));
        var pool = Executors.newFixedThreadPool(2);
        CountDownLatch locked = new CountDownLatch(1), release = new CountDownLatch(1);
        AtomicInteger holderId = new AtomicInteger();
        try {
            var holder = pool.submit(() -> new TransactionTemplate(transactions).execute(status -> {
                if (change.equals("visibility")) {
                    Worry row = worries.findByIdAndDeletedAtIsNull(worry.getId()).orElseThrow();
                    holderId.set(jdbc.queryForObject("SELECT SESSION_ID()", Integer.class));
                    locked.countDown(); awaitRelease(release);
                    row.makeSeniorsOnly();
                } else {
                    Reply row = replies.findByIdAndDeletedAtIsNull(reply.getId()).orElseThrow();
                    holderId.set(jdbc.queryForObject("SELECT SESSION_ID()", Integer.class));
                    locked.countDown(); awaitRelease(release);
                    if (change.equals("delete")) row.delete(); else row.hide();
                }
                return null;
            }));
            assertThat(locked.await(10, TimeUnit.SECONDS)).isTrue();
            var toggle = pool.submit(() -> {
                try { service.toggle(youth.getId(), reply.getId()); return null; }
                catch (BusinessException e) { return e.getErrorCode(); }
            });
            long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
            boolean blocked = false;
            while (!blocked && System.nanoTime() < deadline) {
                Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM INFORMATION_SCHEMA.SESSIONS WHERE BLOCKER_ID = ?", Integer.class, holderId.get());
                blocked = count != null && count > 0;
                if (!blocked) Thread.sleep(20);
            }
            assertThat(blocked).isTrue();
            release.countDown(); holder.get(20, TimeUnit.SECONDS);
            assertThat(toggle.get(20, TimeUnit.SECONDS)).isEqualTo(expected);
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM reply_likes WHERE reply_id = ?", Long.class, reply.getId())).isZero();
        } finally { release.countDown(); pool.shutdownNow(); }
    }

    private void awaitRelease(CountDownLatch release) {
        try {
            if (!release.await(20, TimeUnit.SECONDS)) throw new IllegalStateException("잠금 대기 시간 초과");
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException(e);
        }
    }
}
