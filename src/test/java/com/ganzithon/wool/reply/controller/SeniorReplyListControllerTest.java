package com.ganzithon.wool.reply.controller;

import com.ganzithon.wool.IntegrationTestSupport;
import com.ganzithon.wool.feedback.entity.FollowUp;
import com.ganzithon.wool.feedback.entity.Thanks;
import com.ganzithon.wool.feedback.entity.ThanksStamp;
import com.ganzithon.wool.feedback.repository.FollowUpRepository;
import com.ganzithon.wool.feedback.repository.ThanksRepository;
import com.ganzithon.wool.reply.entity.Reply;
import com.ganzithon.wool.reply.repository.ReplyRepository;
import com.ganzithon.wool.user.entity.AgeGroup;
import com.ganzithon.wool.user.entity.Role;
import com.ganzithon.wool.user.entity.User;
import com.ganzithon.wool.user.repository.UserRepository;
import com.ganzithon.wool.worry.entity.Worry;
import com.ganzithon.wool.worry.entity.WorryTag;
import com.ganzithon.wool.worry.entity.WorryVisibility;
import com.ganzithon.wool.worry.repository.WorryRepository;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.ResultActions;
import org.springframework.transaction.annotation.Transactional;

import java.time.LocalDateTime;
import java.util.UUID;

import static org.hamcrest.Matchers.endsWith;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

// REPLY-006 내가 보낸 답장 목록
@AutoConfigureMockMvc
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class SeniorReplyListControllerTest extends IntegrationTestSupport {

    @Autowired private MockMvc mockMvc;
    @Autowired private UserRepository users;
    @Autowired private WorryRepository worries;
    @Autowired private ReplyRepository replies;
    @Autowired private ThanksRepository thanksRepository;
    @Autowired private FollowUpRepository followUpRepository;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private com.ganzithon.wool.report.service.WorryReportService worryReportService;

    private User youth;
    private User senior;
    private User other;

    // reply_likes는 JPA 엔티티가 없어서 테스트 DB(H2)에 직접 만든다. (다른 공감 테스트와 같은 방식)
    // 다른 테스트 클래스도 같은 테이블을 쓰므로 여기서는 지우지 않는다. 테스트가 넣은 행은 트랜잭션 롤백으로 사라진다.
    @BeforeAll
    void createTables() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS reply_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reply_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL)");
    }

    private static String name(String prefix) {
        return prefix + UUID.randomUUID().toString().substring(0, 6);
    }

    private User newUser(Role role, String prefix) {
        return users.saveAndFlush(User.join(role, role == Role.YOUTH ? AgeGroup.AGE_20S : AgeGroup.AGE_60S, name(prefix)));
    }

    private Worry newWorry(String title) {
        return worries.saveAndFlush(Worry.of(youth, title, "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
    }

    private Reply replyOn(Worry worry, User by) {
        return replies.saveAndFlush(Reply.text(worry, by, "답장"));
    }

    private void like(Reply reply, int count) {
        for (int i = 0; i < count; i++) {
            jdbc.update("INSERT INTO reply_likes (reply_id, user_id, created_at) VALUES (?, ?, ?)",
                    reply.getId(), UUID.randomUUID().toString(), LocalDateTime.now());
        }
    }

    private ResultActions list(User who) throws Exception {
        var request = get("/api/senior/replies");
        return mockMvc.perform(who == null ? request : request.header("X-User-Id", who.getId()));
    }

    @BeforeEach
    void setUp() {
        youth = newUser(Role.YOUTH, "청년");
        senior = newUser(Role.SENIOR, "선배");
        other = newUser(Role.SENIOR, "다른선배");
    }

    @Test
    void 보낸_답장이_없으면_빈_목록이다() throws Exception {
        list(senior)
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value(200))
                .andExpect(jsonPath("$.code").value("SENIOR_200_3"))
                .andExpect(jsonPath("$.message").value("내가 보낸 답장 목록 조회에 성공했습니다."))
                .andExpect(jsonPath("$.data.items.length()").value(0));
    }

    @Test
    void 답장마다_고민_제목과_방식과_공감_수와_고마움_후일담_여부와_시각을_준다() throws Exception {
        Worry worry = newWorry("첫 직장 1년도 안 됐는데 그만두고 싶어요");
        Reply reply = replyOn(worry, senior);
        like(reply, 3);
        thanksRepository.saveAndFlush(Thanks.of(reply, ThanksStamp.GRATEFUL, "고마워요"));
        followUpRepository.saveAndFlush(FollowUp.of(reply, "그 뒤 이야기", WorryVisibility.SENIORS_ONLY));

        list(senior)
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.items.length()").value(1))
                .andExpect(jsonPath("$.data.items[0].replyId").value(reply.getId()))
                .andExpect(jsonPath("$.data.items[0].worryId").value(worry.getId()))
                .andExpect(jsonPath("$.data.items[0].worryTitle").value("첫 직장 1년도 안 됐는데 그만두고 싶어요"))
                .andExpect(jsonPath("$.data.items[0].type").value("TEXT"))
                .andExpect(jsonPath("$.data.items[0].likeCount").value(3))
                .andExpect(jsonPath("$.data.items[0].thanked").value(true))
                .andExpect(jsonPath("$.data.items[0].hasFollowUp").value(true))
                .andExpect(jsonPath("$.data.items[0].createdAt", endsWith("+09:00")))
                // 명세의 여덟 필드 외에 다른 값(답장 내용 등)이 내려가지 않는다.
                .andExpect(jsonPath("$.data.items[0].length()").value(8));
    }

    @Test
    void 고마움과_후일담_여부는_답장마다_따로_정해진다() throws Exception {
        Reply none = replyOn(newWorry("반응 없음"), senior);
        Reply onlyThanks = replyOn(newWorry("고마움만"), senior);
        Reply onlyFollowUp = replyOn(newWorry("후일담만"), senior);
        thanksRepository.saveAndFlush(Thanks.of(onlyThanks, ThanksStamp.HELPED, null));
        followUpRepository.saveAndFlush(FollowUp.of(onlyFollowUp, "후일담", WorryVisibility.PUBLIC));
        like(onlyFollowUp, 2);

        // 최신순이라 마지막에 쓴 후일담만이 맨 앞이다.
        list(senior)
                .andExpect(jsonPath("$.data.items[0].replyId").value(onlyFollowUp.getId()))
                .andExpect(jsonPath("$.data.items[0].thanked").value(false))
                .andExpect(jsonPath("$.data.items[0].hasFollowUp").value(true))
                .andExpect(jsonPath("$.data.items[0].likeCount").value(2))
                .andExpect(jsonPath("$.data.items[1].replyId").value(onlyThanks.getId()))
                .andExpect(jsonPath("$.data.items[1].thanked").value(true))
                .andExpect(jsonPath("$.data.items[1].hasFollowUp").value(false))
                .andExpect(jsonPath("$.data.items[1].likeCount").value(0))
                .andExpect(jsonPath("$.data.items[2].replyId").value(none.getId()))
                .andExpect(jsonPath("$.data.items[2].thanked").value(false))
                .andExpect(jsonPath("$.data.items[2].hasFollowUp").value(false));
    }

    @Test
    void 최신순으로_내려준다() throws Exception {
        Reply first = replyOn(newWorry("처음"), senior);
        Reply second = replyOn(newWorry("두번째"), senior);
        Reply third = replyOn(newWorry("세번째"), senior);

        list(senior)
                .andExpect(jsonPath("$.data.items.length()").value(3))
                .andExpect(jsonPath("$.data.items[0].replyId").value(third.getId()))
                .andExpect(jsonPath("$.data.items[1].replyId").value(second.getId()))
                .andExpect(jsonPath("$.data.items[2].replyId").value(first.getId()));
    }

    @Test
    void 내가_보낸_답장만_보이고_다른_어르신의_답장은_섞이지_않는다() throws Exception {
        Reply mine = replyOn(newWorry("내 답장"), senior);
        Reply theirs = replyOn(newWorry("남의 답장"), other);
        thanksRepository.saveAndFlush(Thanks.of(theirs, ThanksStamp.CHEERED, null));
        like(theirs, 5);

        list(senior)
                .andExpect(jsonPath("$.data.items.length()").value(1))
                .andExpect(jsonPath("$.data.items[0].replyId").value(mine.getId()))
                .andExpect(jsonPath("$.data.items[0].thanked").value(false))
                .andExpect(jsonPath("$.data.items[0].likeCount").value(0));
    }

    @Test
    void 삭제하거나_신고로_숨겨진_답장은_보이지_않는다() throws Exception {
        Reply visible = replyOn(newWorry("보이는 답장"), senior);
        Reply deleted = Reply.text(newWorry("삭제한 답장"), senior, "지움");
        deleted.delete();
        replies.saveAndFlush(deleted);
        Reply hidden = Reply.text(newWorry("숨긴 답장"), senior, "숨김");
        hidden.hide();
        replies.saveAndFlush(hidden);

        list(senior)
                .andExpect(jsonPath("$.data.items.length()").value(1))
                .andExpect(jsonPath("$.data.items[0].replyId").value(visible.getId()));
    }

    @Test
    void 고민을_삭제했거나_신고로_숨겨졌으면_삭제된_고민으로_보이고_반응은_보이지_않는다() throws Exception {
        Worry deletedWorry = newWorry("삭제될 고민");
        Reply onDeleted = replyOn(deletedWorry, senior);
        thanksRepository.saveAndFlush(Thanks.of(onDeleted, ThanksStamp.GRATEFUL, "고마워요"));
        followUpRepository.saveAndFlush(FollowUp.of(onDeleted, "후일담", WorryVisibility.SENIORS_ONLY));
        like(onDeleted, 4);
        deletedWorry.delete();
        worries.saveAndFlush(deletedWorry);

        Worry hiddenWorry = newWorry("숨겨질 고민");
        Reply onHidden = replyOn(hiddenWorry, senior);
        thanksRepository.saveAndFlush(Thanks.of(onHidden, ThanksStamp.HELPED, null));
        followUpRepository.saveAndFlush(FollowUp.of(onHidden, "후일담", WorryVisibility.PUBLIC));
        like(onHidden, 2);
        jdbc.update("UPDATE worries SET hidden = TRUE WHERE id = ?", hiddenWorry.getId());

        // 최신순: 숨겨진 고민에 단 답장이 먼저다.
        list(senior)
                .andExpect(jsonPath("$.data.items.length()").value(2))
                .andExpect(jsonPath("$.data.items[0].replyId").value(onHidden.getId()))
                .andExpect(jsonPath("$.data.items[0].worryTitle").value("삭제된 고민"))
                .andExpect(jsonPath("$.data.items[0].likeCount").value(0))
                .andExpect(jsonPath("$.data.items[0].thanked").value(false))
                .andExpect(jsonPath("$.data.items[0].hasFollowUp").value(false))
                .andExpect(jsonPath("$.data.items[1].replyId").value(onDeleted.getId()))
                .andExpect(jsonPath("$.data.items[1].worryId").value(deletedWorry.getId()))
                .andExpect(jsonPath("$.data.items[1].worryTitle").value("삭제된 고민"))
                .andExpect(jsonPath("$.data.items[1].likeCount").value(0))
                .andExpect(jsonPath("$.data.items[1].thanked").value(false))
                .andExpect(jsonPath("$.data.items[1].hasFollowUp").value(false));
    }

    @Test
    void 손편지와_말_답장도_방식을_구분해_보여준다() throws Exception {
        replies.saveAndFlush(Reply.letter(newWorry("손편지"), senior, "/files/letters/a.jpg"));
        replies.saveAndFlush(Reply.voice(newWorry("말"), senior, "말로 한 답장"));

        list(senior)
                .andExpect(jsonPath("$.data.items[0].type").value("VOICE"))
                .andExpect(jsonPath("$.data.items[1].type").value("LETTER"));
    }

    @Test
    void 헤더가_없으면_401_청년이면_403이다() throws Exception {
        list(null).andExpect(status().isUnauthorized()).andExpect(jsonPath("$.code").value("USER_401_001"));
        list(youth).andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("USER_403_001"));
    }
    @Test
    void 고민_신고_후_어르신_목록에서_고민과_마음_정보를_가린다() throws Exception {
        Worry worry = newWorry("신고할 고민");
        Reply reply = replyOn(worry, senior);
        thanksRepository.saveAndFlush(Thanks.of(reply, ThanksStamp.GRATEFUL, "감사해요"));
        followUpRepository.saveAndFlush(FollowUp.of(reply, "후일담", WorryVisibility.PUBLIC));
        like(reply, 1);
        worryReportService.report(senior, worry.getId(), com.ganzithon.wool.report.entity.WorryReportReason.AD);
        worries.flush();
        list(senior).andExpect(status().isOk()).andExpect(jsonPath("$.data.items[0].worryTitle").value("삭제된 고민"))
                .andExpect(jsonPath("$.data.items[0].likeCount").value(0))
                .andExpect(jsonPath("$.data.items[0].thanked").value(false))
                .andExpect(jsonPath("$.data.items[0].hasFollowUp").value(false));
    }

}
