import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.endsWith;
import static org.hamcrest.Matchers.nullValue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

// FEEDBACK-001 답장 상세 조회
@AutoConfigureMockMvc
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class ReplyViewControllerTest extends IntegrationTestSupport {

    // 고민 상세(조회 뒤 새 답장 표시 확인용)가 읽는 좋아요 표는 엔티티가 없어 H2에는 직접 만든다.
    @BeforeAll
    void createTables() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS worry_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, worry_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS reply_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reply_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL)");
    }

    @AfterAll
    void dropTables() {
        jdbc.execute("DROP TABLE IF EXISTS reply_likes");
        jdbc.execute("DROP TABLE IF EXISTS worry_likes");
    }

    @Autowired private MockMvc mockMvc;
    @Autowired private UserRepository users;
    @Autowired private WorryRepository worries;
    @Autowired private ReplyRepository replies;
    @Autowired private ThanksRepository thanksRepository;
    @Autowired private FollowUpRepository followUpRepository;
    @Autowired private EntityManager entityManager;
    @Autowired private JdbcTemplate jdbc;

    private User youth;
    private User otherYouth;
    private User senior;
    private Worry worry;
    private Reply reply;

    private static String name(String prefix) {
        return prefix + UUID.randomUUID().toString().substring(0, 6);
    }

    private User newUser(Role role, String prefix) {
        return users.saveAndFlush(User.join(role, role == Role.YOUTH ? AgeGroup.AGE_20S : AgeGroup.AGE_70S, name(prefix)));
    }

    private ResultActions view(User who, Long replyId) throws Exception {
        var request = get("/api/replies/{replyId}", replyId);
        return mockMvc.perform(who == null ? request : request.header("X-User-Id", who.getId()));
    }

    private ResultActions view() throws Exception {
        return view(youth, reply.getId());
    }

    private Reply reload() {
        entityManager.flush();
        entityManager.clear();
        return replies.findById(reply.getId()).orElseThrow();
    }

    private void sendThanks() {
        thanksRepository.saveAndFlush(Thanks.of(reply, ThanksStamp.GRATEFUL, "고마워요"));
    }

    private void sendFollowUp() {
        followUpRepository.saveAndFlush(FollowUp.of(reply, "그 뒤 이야기", WorryVisibility.PUBLIC));
    }

    @BeforeEach
    void setUp() {
        youth = newUser(Role.YOUTH, "청년");
        otherYouth = newUser(Role.YOUTH, "다른청년");
        senior = newUser(Role.SENIOR, "선배");
        worry = worries.saveAndFlush(Worry.of(youth, "제목", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        reply = replies.saveAndFlush(Reply.text(worry, senior, "  원문 그대로의 답장  "));
    }

    // ---------- 응답 ----------

    @Test
    void 첫_조회는_답장_내용과_선배_정보를_주고_고마움만_보여준다() throws Exception {
        view()
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value(200))
                .andExpect(jsonPath("$.code").value("REPLY_200_1"))
                .andExpect(jsonPath("$.message").value("답장 조회에 성공했습니다."))
                .andExpect(jsonPath("$.data.replyId").value(reply.getId()))
                .andExpect(jsonPath("$.data.worryId").value(worry.getId()))
                .andExpect(jsonPath("$.data.type").value("TEXT"))
                // 답장 원문은 다듬지 않고 그대로 준다.
                .andExpect(jsonPath("$.data.content").value("  원문 그대로의 답장  "))
                .andExpect(jsonPath("$.data.imageUrl", nullValue()))
                .andExpect(jsonPath("$.data.senior.nickname").value(senior.getNickname()))
                .andExpect(jsonPath("$.data.senior.ageGroup").value("70S"))
                .andExpect(jsonPath("$.data.isFirstView").value(true))
                .andExpect(jsonPath("$.data.availableActions.length()").value(1))
                .andExpect(jsonPath("$.data.availableActions[0]").value("THANKS"))
                .andExpect(jsonPath("$.data.thanks", nullValue()))
                .andExpect(jsonPath("$.data.followUp", nullValue()))
                // 시각은 서울 기준 +09:00이 붙은 ISO 8601로 내려간다.
                .andExpect(jsonPath("$.data.createdAt").value(endsWith("+09:00")))
                // 명세의 열한 개 필드 외에 다른 값이 내려가지 않는다.
                .andExpect(jsonPath("$.data.length()").value(11));
    }

    @Test
    void 손편지는_본문이_null이고_이미지_주소를_준다() throws Exception {
        reply = replies.saveAndFlush(Reply.letter(
                worries.saveAndFlush(Worry.of(youth, "다른 고민", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC)),
                senior, "https://cdn.example.com/letters/501.jpg"));

        view()
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.data.type").value("LETTER"))
                .andExpect(jsonPath("$.data.content", nullValue()))
                .andExpect(jsonPath("$.data.imageUrl").value("https://cdn.example.com/letters/501.jpg"));
    }

    @Test
    void 음성_답장도_본문을_준다() throws Exception {
        reply = replies.saveAndFlush(Reply.voice(
                worries.saveAndFlush(Worry.of(youth, "음성 고민", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC)),
                senior, "말로 한 답장"));

        view()
                .andExpect(jsonPath("$.data.type").value("VOICE"))
                .andExpect(jsonPath("$.data.content").value("말로 한 답장"))
                .andExpect(jsonPath("$.data.imageUrl", nullValue()));
    }

    // ---------- 최초 조회 시각과 isFirstView ----------

    @Test
    void 첫_조회에_최초_조회_시각을_기록하고_다시_조회해도_바뀌지_않는다() throws Exception {
        assertThat(reload().getFirstViewedAt()).isNull();

        view().andExpect(jsonPath("$.data.isFirstView").value(true));
        var firstViewedAt = reload().getFirstViewedAt();
        assertThat(firstViewedAt).isNotNull();

        view().andExpect(jsonPath("$.data.isFirstView").value(false));
        view().andExpect(jsonPath("$.data.isFirstView").value(false));
        assertThat(reload().getFirstViewedAt()).isEqualTo(firstViewedAt);
    }

    @Test
    void 조회하면_고민_상세의_새_답장_표시가_꺼진다() throws Exception {
        var detail = get("/api/worries/{worryId}", worry.getId()).header("X-User-Id", youth.getId());
        mockMvc.perform(detail).andExpect(jsonPath("$.data.replies[0].isNew").value(true));

        view();

        mockMvc.perform(detail).andExpect(jsonPath("$.data.replies[0].isNew").value(false));
    }

    // ---------- availableActions ----------

    @Test
    void 재조회에_둘_다_안_보냈으면_고마움과_후일담을_보여준다() throws Exception {
        view();

        view()
                .andExpect(jsonPath("$.data.isFirstView").value(false))
                .andExpect(jsonPath("$.data.availableActions.length()").value(2))
                .andExpect(jsonPath("$.data.availableActions[0]").value("THANKS"))
                .andExpect(jsonPath("$.data.availableActions[1]").value("FOLLOW_UP"));
    }

    @Test
    void 재조회에_고마움만_보냈으면_후일담만_보여주고_고마움을_함께_준다() throws Exception {
        view();
        sendThanks();

        view()
                .andExpect(jsonPath("$.data.availableActions.length()").value(1))
                .andExpect(jsonPath("$.data.availableActions[0]").value("FOLLOW_UP"))
                .andExpect(jsonPath("$.data.thanks.stamp").value("GRATEFUL"))
                .andExpect(jsonPath("$.data.thanks.message").value("고마워요"))
                .andExpect(jsonPath("$.data.thanks.createdAt").value(endsWith("+09:00")))
                .andExpect(jsonPath("$.data.thanks.length()").value(3))
                .andExpect(jsonPath("$.data.followUp", nullValue()));
    }

    @Test
    void 재조회에_후일담만_보냈으면_고마움만_보여주고_후일담을_함께_준다() throws Exception {
        view();
        sendFollowUp();

        view()
                .andExpect(jsonPath("$.data.availableActions.length()").value(1))
                .andExpect(jsonPath("$.data.availableActions[0]").value("THANKS"))
                .andExpect(jsonPath("$.data.thanks", nullValue()))
                .andExpect(jsonPath("$.data.followUp.content").value("그 뒤 이야기"))
                .andExpect(jsonPath("$.data.followUp.visibility").value("PUBLIC"))
                .andExpect(jsonPath("$.data.followUp.createdAt").value(endsWith("+09:00")))
                .andExpect(jsonPath("$.data.followUp.length()").value(3));
    }

    @Test
    void 둘_다_보냈으면_보여줄_버튼이_없다() throws Exception {
        view();
        sendThanks();
        sendFollowUp();

        view()
                .andExpect(jsonPath("$.data.availableActions.length()").value(0))
                .andExpect(jsonPath("$.data.thanks.stamp").value("GRATEFUL"))
                .andExpect(jsonPath("$.data.followUp.content").value("그 뒤 이야기"));
    }

    // 고마움을 보내기 전에 화면을 거치지 않은 경우처럼 첫 조회인데 이미 보낸 것이 있어도, 첫 조회는 고마움만 다룬다.
    @Test
    void 첫_조회에_이미_고마움을_보냈으면_버튼이_없고_후일담은_보여주지_않는다() throws Exception {
        sendThanks();

        view()
                .andExpect(jsonPath("$.data.isFirstView").value(true))
                .andExpect(jsonPath("$.data.availableActions.length()").value(0));
    }

    @Test
    void 첫_조회에_후일담만_보냈어도_후일담_버튼은_없고_고마움만_보여준다() throws Exception {
        sendFollowUp();

        view()
                .andExpect(jsonPath("$.data.isFirstView").value(true))
                .andExpect(jsonPath("$.data.availableActions.length()").value(1))
                .andExpect(jsonPath("$.data.availableActions[0]").value("THANKS"));
    }

    // ---------- 권한과 오류 ----------

    @Test
    void 헤더가_없으면_401_어르신이면_403이다() throws Exception {
        view(null, reply.getId()).andExpect(status().isUnauthorized()).andExpect(jsonPath("$.code").value("USER_401_001"));
        view(senior, reply.getId()).andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("USER_403_001"));
        assertThat(reload().getFirstViewedAt()).isNull();
    }

    @Test
    void 고민_작성자가_아니면_403이고_조회_시각을_남기지_않는다() throws Exception {
        view(otherYouth, reply.getId())
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.code").value("REPLY_403_001"));

        assertThat(reload().getFirstViewedAt()).isNull();
    }

    @Test
    void 신고로_숨긴_답장은_403이고_조회_시각을_남기지_않는다() throws Exception {
        reply.hide();
        replies.saveAndFlush(reply);

        view().andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("REPLY_403_001"));

        assertThat(reload().getFirstViewedAt()).isNull();
    }

    @Test
    void 없는_답장_삭제한_답장_삭제한_고민_숨겨진_고민은_404이다() throws Exception {
        view(youth, 999_999L).andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("REPLY_404_001"));

        Reply deleted = replies.saveAndFlush(Reply.text(
                worries.saveAndFlush(Worry.of(youth, "지울 고민", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC)), senior, "지움"));
        deleted.delete();
        replies.saveAndFlush(deleted);
        view(youth, deleted.getId()).andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("REPLY_404_001"));

        Worry deletedWorry = worries.saveAndFlush(Worry.of(youth, "지운 고민", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Reply onDeletedWorry = replies.saveAndFlush(Reply.text(deletedWorry, senior, "답장"));
        deletedWorry.delete();
        worries.saveAndFlush(deletedWorry);
        view(youth, onDeletedWorry.getId()).andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("REPLY_404_001"));

        jdbc.update("UPDATE worries SET hidden = TRUE WHERE id = ?", worry.getId());
        entityManager.clear();
        view().andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("REPLY_404_001"));
    }
}
