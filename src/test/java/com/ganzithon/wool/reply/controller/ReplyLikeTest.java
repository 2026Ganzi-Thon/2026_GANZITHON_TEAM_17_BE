package com.ganzithon.wool.reply.controller;

import com.ganzithon.wool.IntegrationTestSupport;
import com.ganzithon.wool.reply.entity.Reply;
import com.ganzithon.wool.reply.repository.ReplyRepository;
import com.ganzithon.wool.user.entity.*;
import com.ganzithon.wool.user.repository.UserRepository;
import com.ganzithon.wool.worry.entity.*;
import com.ganzithon.wool.worry.repository.WorryRepository;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@AutoConfigureMockMvc
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class ReplyLikeTest extends IntegrationTestSupport {
    @Autowired MockMvc mvc;
    @Autowired JdbcTemplate jdbc;
    @Autowired UserRepository users;
    @Autowired WorryRepository worries;
    @Autowired ReplyRepository replies;

    @BeforeAll void setup() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS reply_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reply_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL, UNIQUE(reply_id,user_id))");
    }
    @AfterAll void cleanup() { jdbc.execute("DROP TABLE IF EXISTS reply_likes"); }

    @Test void 토글과_접근_제한() throws Exception {
        var youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "공감청년"));
        var senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "공감선배"));
        var worry = worries.saveAndFlush(Worry.of(youth, "제목", "내용", WorryTag.CAREER, WorryVisibility.PUBLIC));
        var reply = replies.saveAndFlush(Reply.text(worry, senior, "답장"));
        mvc.perform(post("/api/replies/{id}/likes",reply.getId()).header("X-User-Id",youth.getId()))
            .andExpect(status().isOk()).andExpect(jsonPath("$.data.likeCount").value(1)).andExpect(jsonPath("$.data.likedByMe").value(true));
        mvc.perform(post("/api/replies/{id}/likes",reply.getId()).header("X-User-Id",youth.getId()))
            .andExpect(status().isOk()).andExpect(jsonPath("$.data.likeCount").value(0)).andExpect(jsonPath("$.data.likedByMe").value(false));
        reply.hide(); replies.flush();
        mvc.perform(post("/api/replies/{id}/likes",reply.getId()).header("X-User-Id",youth.getId())).andExpect(status().isForbidden());
        mvc.perform(post("/api/replies/{id}/likes",reply.getId()).header("X-User-Id",senior.getId())).andExpect(status().isForbidden());
        mvc.perform(post("/api/replies/{id}/likes",reply.getId())).andExpect(status().isUnauthorized());
        reply.delete(); replies.flush();
        mvc.perform(post("/api/replies/{id}/likes",reply.getId()).header("X-User-Id",youth.getId())).andExpect(status().isNotFound());
    }
}
