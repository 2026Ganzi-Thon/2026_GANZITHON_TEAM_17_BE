package com.ganzithon.wool.worry.controller;

import com.ganzithon.wool.IntegrationTestSupport;
import com.ganzithon.wool.reply.entity.Reply;
import com.ganzithon.wool.reply.repository.ReplyRepository;
import com.ganzithon.wool.user.entity.AgeGroup;
import com.ganzithon.wool.user.entity.Role;
import com.ganzithon.wool.user.entity.User;
import com.ganzithon.wool.user.repository.UserRepository;
import com.ganzithon.wool.worry.entity.Worry;
import com.ganzithon.wool.worry.entity.WorryTag;
import com.ganzithon.wool.worry.entity.WorryVisibility;
import com.ganzithon.wool.worry.repository.WorryRepository;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@AutoConfigureMockMvc
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class WorryDetailTest extends IntegrationTestSupport {
    @Autowired private MockMvc mvc;
    @Autowired private UserRepository users;
    @Autowired private WorryRepository worries;
    @Autowired private ReplyRepository replies;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private EntityManager entityManager;

    @BeforeAll
    void createTables() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS worry_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, worry_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS reply_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reply_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS follow_ups (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reply_id BIGINT NOT NULL, content VARCHAR(1000) NOT NULL, visibility VARCHAR(20) NOT NULL, created_at TIMESTAMP NOT NULL)");
    }

    @AfterAll
    void dropTables() {
        jdbc.execute("DROP TABLE IF EXISTS reply_likes");
        jdbc.execute("DROP TABLE IF EXISTS follow_ups");
        jdbc.execute("DROP TABLE IF EXISTS worry_likes");
    }

    @Test
    void 작성자와_다른_청년의_답장과_후일담_노출을_구분한다() throws Exception {
        User author = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "상세작성자"));
        User reader = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_30S, "상세조회자"));
        User senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "상세선배1"));
        User senior2 = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "상세선배2"));
        User senior3 = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "상세선배3"));
        Worry worry = worries.saveAndFlush(Worry.of(author, "제목", "본문 그대로", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Reply reply = replies.saveAndFlush(Reply.text(worry, senior, "답장"));
        Reply hidden = Reply.text(worry, senior2, "숨긴 답장"); hidden.hide(); replies.saveAndFlush(hidden);
        Reply deleted = replies.saveAndFlush(Reply.text(worry, senior3, "삭제 답장")); deleted.delete(); replies.flush();
        jdbc.update("INSERT INTO worry_likes(worry_id,user_id,created_at) VALUES (?,?,CURRENT_TIMESTAMP)", worry.getId(), reader.getId());
        jdbc.update("INSERT INTO reply_likes(reply_id,user_id,created_at) VALUES (?,?,CURRENT_TIMESTAMP)", reply.getId(), reader.getId());
        jdbc.update("INSERT INTO follow_ups(reply_id,content,visibility,created_at) VALUES (?,?,?,CURRENT_TIMESTAMP)", reply.getId(), "비공개 후일담", "SENIORS_ONLY");
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", author.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.code").value("WORRY_200_2"))
                .andExpect(jsonPath("$.data.isMine").value(true)).andExpect(jsonPath("$.data.canEdit").value(false))
                .andExpect(jsonPath("$.data.replies.length()").value(1)).andExpect(jsonPath("$.data.replies[0].isNew").value(true))
                .andExpect(jsonPath("$.data.replies[0].followUp.content").value("비공개 후일담"));
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", reader.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.isMine").value(false))
                .andExpect(jsonPath("$.data.likedByMe").value(true)).andExpect(jsonPath("$.data.likeCount").value(1))
                .andExpect(jsonPath("$.data.replies[0].likedByMe").value(true)).andExpect(jsonPath("$.data.replies[0].likeCount").value(1))
                .andExpect(jsonPath("$.data.replies[0].isNew").value(false)).andExpect(jsonPath("$.data.replies[0].followUp").isEmpty());
        jdbc.update("UPDATE follow_ups SET visibility = 'PUBLIC' WHERE reply_id = ?", reply.getId());
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", reader.getId()))
                .andExpect(jsonPath("$.data.replies[0].followUp.content").value("비공개 후일담"));
    }

    @Test
    void 숨김과_비공개_삭제_권한을_구분한다() throws Exception {
        User author = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "상세소유자"));
        User reader = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "상세방문자"));
        User senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "상세어르신"));
        Worry worry = worries.saveAndFlush(Worry.of(author, "제목", "본문", WorryTag.CAREER, WorryVisibility.SENIORS_ONLY));
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", author.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.canEdit").value(true));
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", reader.getId()))
                .andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("WORRY_403_001"));
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", senior.getId())).andExpect(status().isForbidden());
        mvc.perform(get("/api/worries/{id}", worry.getId())).andExpect(status().isUnauthorized());
        jdbc.update("UPDATE worries SET hidden = true WHERE id = ?", worry.getId());
        entityManager.refresh(worry);
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", reader.getId()))
                .andExpect(status().isNotFound());
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", author.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.hidden").value(true)).andExpect(jsonPath("$.data.canEdit").value(false));
        worry.delete(); worries.flush();
        mvc.perform(get("/api/worries/{id}", worry.getId()).header("X-User-Id", author.getId())).andExpect(status().isNotFound());
    }
}
