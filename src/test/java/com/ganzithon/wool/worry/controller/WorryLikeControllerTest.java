package com.ganzithon.wool.worry.controller;

import com.ganzithon.wool.IntegrationTestSupport;
import com.ganzithon.wool.user.entity.AgeGroup;
import com.ganzithon.wool.user.entity.Role;
import com.ganzithon.wool.user.entity.User;
import com.ganzithon.wool.user.repository.UserRepository;
import com.ganzithon.wool.worry.entity.Worry;
import com.ganzithon.wool.worry.entity.WorryTag;
import com.ganzithon.wool.worry.entity.WorryVisibility;
import com.ganzithon.wool.worry.repository.WorryRepository;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@AutoConfigureMockMvc
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class WorryLikeControllerTest extends IntegrationTestSupport {
    @Autowired private MockMvc mvc;
    @Autowired private UserRepository users;
    @Autowired private WorryRepository worries;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private EntityManager entityManager;

    @BeforeAll
    void createTable() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS worry_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, worry_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL, UNIQUE(worry_id, user_id))");
    }

    @AfterAll
    void dropTable() {
        jdbc.execute("DROP TABLE IF EXISTS worry_likes");
    }

    @Test
    void 좋아요_추가와_취소를_반영하고_다른_사용자는_유지한다() throws Exception {
        User author = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "좋아요작성"));
        User other = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_30S, "좋아요다른"));
        Worry worry = worries.saveAndFlush(Worry.of(author, "제목", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        mvc.perform(post("/api/worries/{id}/likes", worry.getId()).header("X-User-Id", other.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.code").value("LIKE_200_1"))
                .andExpect(jsonPath("$.data.likeCount").value(1)).andExpect(jsonPath("$.data.likedByMe").value(true));
        mvc.perform(post("/api/worries/{id}/likes", worry.getId()).header("X-User-Id", author.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.likeCount").value(2));
        mvc.perform(get("/api/worries/public").header("X-User-Id", author.getId()))
                .andExpect(jsonPath("$.data.items[0].likeCount").value(2));
        mvc.perform(post("/api/worries/{id}/likes", worry.getId()).header("X-User-Id", other.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.likeCount").value(1))
                .andExpect(jsonPath("$.data.likedByMe").value(false));
    }

    @Test
    void 인증과_고민_상태를_확인한다() throws Exception {
        User youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "좋아요청년"));
        User senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "좋아요선배"));
        Worry hidden = worries.saveAndFlush(Worry.of(youth, "숨김", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Worry deleted = worries.saveAndFlush(Worry.of(youth, "삭제", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Worry secret = worries.saveAndFlush(Worry.of(youth, "비공개", "본문", WorryTag.CAREER, WorryVisibility.SENIORS_ONLY));
        jdbc.update("UPDATE worries SET hidden = true WHERE id = ?", hidden.getId());
        deleted.delete(); worries.flush();
        entityManager.clear();
        mvc.perform(post("/api/worries/{id}/likes", hidden.getId()).header("X-User-Id", youth.getId()))
                .andExpect(status().isNotFound()).andExpect(jsonPath("$.code").value("WORRY_404_001"));
        mvc.perform(post("/api/worries/{id}/likes", deleted.getId()).header("X-User-Id", youth.getId())).andExpect(status().isNotFound());
        mvc.perform(post("/api/worries/{id}/likes", 99999999L).header("X-User-Id", youth.getId())).andExpect(status().isNotFound());
        mvc.perform(post("/api/worries/{id}/likes", secret.getId()).header("X-User-Id", youth.getId()))
                .andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("WORRY_403_001"));
        mvc.perform(post("/api/worries/{id}/likes", secret.getId()).header("X-User-Id", senior.getId()))
                .andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("USER_403_001"));
        mvc.perform(post("/api/worries/{id}/likes", secret.getId())).andExpect(status().isUnauthorized());
    }
}
