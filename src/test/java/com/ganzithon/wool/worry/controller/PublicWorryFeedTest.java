package com.ganzithon.wool.worry.controller;

import com.ganzithon.wool.IntegrationTestSupport;
import com.ganzithon.wool.reply.entity.Reply;
import com.ganzithon.wool.reply.repository.ReplyRepository;
import com.ganzithon.wool.user.entity.AgeGroup;
import com.ganzithon.wool.user.entity.Role;
import com.ganzithon.wool.user.entity.User;
import com.ganzithon.wool.user.repository.UserRepository;
import com.ganzithon.wool.worry.entity.Worry;
import com.ganzithon.wool.worry.entity.WorryTag;
import com.ganzithon.wool.worry.entity.WorryVisibility;
import com.ganzithon.wool.worry.repository.WorryRepository;
import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.transaction.annotation.Transactional;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.*;

@AutoConfigureMockMvc
@Transactional
@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class PublicWorryFeedTest extends IntegrationTestSupport {
    @Autowired private MockMvc mvc;
    @Autowired private UserRepository users;
    @Autowired private WorryRepository worries;
    @Autowired private ReplyRepository replies;
    @Autowired private JdbcTemplate jdbc;

    @BeforeAll
    void createLikes() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS worry_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, worry_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL)");
    }

    @AfterAll
    void dropLikes() {
        jdbc.execute("DROP TABLE IF EXISTS worry_likes");
    }

    @Test
    void 공개_고민을_필터링하고_답장과_좋아요를_각각_집계한다() throws Exception {
        User youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "피드청년"));
        User senior = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "피드선배"));
        User senior2 = users.saveAndFlush(User.join(Role.SENIOR, AgeGroup.AGE_60S, "피드선배2"));
        Worry first = worries.saveAndFlush(Worry.of(youth, "첫 공개", "내용", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Worry second = worries.saveAndFlush(Worry.of(youth, "둘 공개", "내용", WorryTag.MIND, WorryVisibility.PUBLIC));
        worries.saveAndFlush(Worry.of(youth, "비공개", "내용", WorryTag.CAREER, WorryVisibility.SENIORS_ONLY));
        Worry hidden = worries.saveAndFlush(Worry.of(youth, "숨김", "내용", WorryTag.CAREER, WorryVisibility.PUBLIC));
        Worry deleted = worries.saveAndFlush(Worry.of(youth, "삭제", "내용", WorryTag.CAREER, WorryVisibility.PUBLIC));
        deleted.delete(); worries.flush();
        jdbc.update("UPDATE worries SET hidden = TRUE WHERE id = ?", hidden.getId());
        replies.saveAndFlush(Reply.text(first, senior, "답장"));
        Reply hiddenReply = Reply.text(first, senior2, "숨김 답장"); hiddenReply.hide(); replies.saveAndFlush(hiddenReply);
        jdbc.update("INSERT INTO worry_likes(worry_id,user_id,created_at) VALUES (?,?,CURRENT_TIMESTAMP)", first.getId(), youth.getId());
        jdbc.update("INSERT INTO worry_likes(worry_id,user_id,created_at) VALUES (?,?,CURRENT_TIMESTAMP)", first.getId(), senior.getId());
        mvc.perform(get("/api/worries/public").header("X-User-Id", youth.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.code").value("WORRY_200_4"))
                .andExpect(jsonPath("$.data.items.length()").value(2))
                .andExpect(jsonPath("$.data.items[0].worryId").value(second.getId()))
                .andExpect(jsonPath("$.data.items[1].worryId").value(first.getId()))
                .andExpect(jsonPath("$.data.items[1].replyCount").value(1))
                .andExpect(jsonPath("$.data.items[1].likeCount").value(2))
                .andExpect(jsonPath("$.data.items[1].preview").doesNotExist());
        mvc.perform(get("/api/worries/public").param("tag", "CAREER").header("X-User-Id", youth.getId()))
                .andExpect(status().isOk()).andExpect(jsonPath("$.data.items.length()").value(1))
                .andExpect(jsonPath("$.data.items[0].worryId").value(first.getId()));
        mvc.perform(get("/api/worries/public").param("tag", "BAD").header("X-User-Id", youth.getId()))
                .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value("COMMON_400"));
        mvc.perform(get("/api/worries/public").param("tag", "").header("X-User-Id", youth.getId()))
                .andExpect(status().isBadRequest()).andExpect(jsonPath("$.code").value("COMMON_400"));
        mvc.perform(get("/api/worries/public")).andExpect(status().isUnauthorized());
        mvc.perform(get("/api/worries/public").header("X-User-Id", senior.getId())).andExpect(status().isForbidden());
    }
}
