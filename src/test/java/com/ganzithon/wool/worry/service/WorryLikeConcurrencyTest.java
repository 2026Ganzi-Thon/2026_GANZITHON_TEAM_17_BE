import java.util.List;
import java.util.concurrent.CountDownLatch;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;
import java.util.concurrent.atomic.AtomicInteger;

import static org.assertj.core.api.Assertions.assertThat;

@TestInstance(TestInstance.Lifecycle.PER_CLASS)
class WorryLikeConcurrencyTest extends IntegrationTestSupport {
    @Autowired private UserRepository users;
    @Autowired private WorryRepository worries;
    @Autowired private WorryLikeService service;
    @Autowired private JdbcTemplate jdbc;
    @Autowired private DatabaseCleaner cleaner;
    @Autowired private PlatformTransactionManager transactions;

    @BeforeAll
    void createTable() {
        jdbc.execute("CREATE TABLE IF NOT EXISTS worry_likes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, worry_id BIGINT NOT NULL, user_id VARCHAR(36) NOT NULL, created_at TIMESTAMP NOT NULL, UNIQUE(worry_id, user_id))");
    }

    @AfterAll
    void clean() {
        cleaner.clean();
        jdbc.execute("DROP TABLE IF EXISTS worry_likes");
    }

    @Test
    void 같은_사용자의_동시_토글은_추가와_취소로_순서대로_처리된다() throws Exception {
        User youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "동시좋아요"));
        Worry worry = worries.saveAndFlush(Worry.of(youth, "제목", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        var pool = Executors.newFixedThreadPool(2);
        try {
            CountDownLatch ready = new CountDownLatch(2);
            CountDownLatch go = new CountDownLatch(1);
            java.util.concurrent.Callable<WorryLikeResponse> task = () -> {
                ready.countDown();
                go.await();
                return service.toggle(youth.getId(), worry.getId());
            };
            var first = pool.submit(task);
            var second = pool.submit(task);
            assertThat(ready.await(10, TimeUnit.SECONDS)).isTrue();
            go.countDown();
            var results = List.of(first.get(30, TimeUnit.SECONDS), second.get(30, TimeUnit.SECONDS));
            assertThat(results).extracting(WorryLikeResponse::likedByMe).containsExactlyInAnyOrder(true, false);
            assertThat(results).extracting(WorryLikeResponse::likeCount).containsExactlyInAnyOrder(1L, 0L);
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM worry_likes WHERE worry_id = ?", Long.class, worry.getId())).isZero();
        } finally {
            pool.shutdownNow();
        }
    }

    @Test
    void 공개_범위_변경을_기다린_뒤_좋아요를_거부한다() throws Exception {
        User youth = users.saveAndFlush(User.join(Role.YOUTH, AgeGroup.AGE_20S, "동시비공개"));
        Worry worry = worries.saveAndFlush(Worry.of(youth, "제목", "본문", WorryTag.CAREER, WorryVisibility.PUBLIC));
        var pool = Executors.newFixedThreadPool(2);
        CountDownLatch locked = new CountDownLatch(1);
        CountDownLatch release = new CountDownLatch(1);
        AtomicInteger holderId = new AtomicInteger();
        try {
            var holder = pool.submit(() -> new TransactionTemplate(transactions).execute(status -> {
                Worry lockedWorry = worries.findByIdAndDeletedAtIsNull(worry.getId()).orElseThrow();
                holderId.set(jdbc.queryForObject("SELECT SESSION_ID()", Integer.class));
                locked.countDown();
                try {
                    if (!release.await(20, TimeUnit.SECONDS)) throw new IllegalStateException("잠금 대기 시간 초과");
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                    throw new IllegalStateException(e);
                }
                lockedWorry.makeSeniorsOnly();
                return null;
            }));
            assertThat(locked.await(10, TimeUnit.SECONDS)).isTrue();
            var toggle = pool.submit(() -> {
                try {
                    service.toggle(youth.getId(), worry.getId());
                    return null;
                } catch (BusinessException e) {
                    return e.getErrorCode();
                }
            });
            long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(10);
            boolean blocked = false;
            while (System.nanoTime() < deadline && !blocked) {
                Integer waiting = jdbc.queryForObject("SELECT COUNT(*) FROM INFORMATION_SCHEMA.SESSIONS WHERE BLOCKER_ID = ?", Integer.class, holderId.get());
                blocked = waiting != null && waiting > 0;
                if (!blocked) Thread.sleep(20);
            }
            assertThat(blocked).isTrue();
            release.countDown();
            holder.get(20, TimeUnit.SECONDS);
            assertThat(toggle.get(20, TimeUnit.SECONDS)).isEqualTo(WorryErrorCode.FORBIDDEN_VIEW);
            assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM worry_likes WHERE worry_id = ?", Long.class, worry.getId())).isZero();
        } finally {
            release.countDown();
            pool.shutdownNow();
        }
    }
}
